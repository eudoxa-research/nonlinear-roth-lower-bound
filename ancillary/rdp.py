"""Restricted-state dynamic program for Younis chains at modulus m (lower-bound search).
States = symmetrised square-sets sigma(R) = sq(R) u -sq(R), encoded as bitmasks over negation pairs.
Candidates for a state F are generated by (a) enumerating maximum cliques of G_F, (b) shrinking their states by
one pair, (c) forbidding one square class in the next state.  Value iteration over the discovered states gives a
lower bound on W(S), and following the policy gives an explicit admissible chain."""
import sys, math, subprocess, time, json, pickle, random
from collections import defaultdict

m = int(sys.argv[1]) if len(sys.argv) > 1 else 145
ROUNDS = int(sys.argv[2]) if len(sys.argv) > 2 else 6
ENUMCAP = int(sys.argv[3]) if len(sys.argv) > 3 else 3000
TOPN = int(sys.argv[4]) if len(sys.argv) > 4 else 12
SEED = int(sys.argv[5]) if len(sys.argv) > 5 else 0
MINPAIRS = int(sys.argv[6]) if len(sys.argv) > 6 else 8
KTOP = int(sys.argv[7]) if len(sys.argv) > 7 else 60
BUDGET = int(sys.argv[8]) if len(sys.argv) > 8 else 0
TWOPAIR = int(sys.argv[9]) if len(sys.argv) > 9 else 0
tried_targets = {}
random.seed(SEED)
SQ = sorted({(x*x) % m for x in range(m)} - {0})
Sset = set(SQ)
pairs = []; seen = set()
for s in SQ:
    if s in seen: continue
    pairs.append((s, (-s) % m)); seen |= {s, (-s) % m}
P = len(pairs); S = (1 << P) - 1
pair_of = {}
for i, (a, b) in enumerate(pairs): pair_of[a] = i; pair_of[b] = i
assert all(((-s) % m) in Sset for s in SQ), "-1 must be a square"
sqrt_pairs = defaultdict(list)          # pair index -> residues d with d^2 in that pair
for d in range(1, m):
    sqrt_pairs[pair_of[(d*d) % m]].append(d)
log = math.log

def fset(F):
    out = []
    for i in range(P):
        if F >> i & 1: out += list(pairs[i])
    return out
def Dset(Fp):
    out = []
    for i in range(P):
        if not (Fp >> i & 1): out += sqrt_pairs[i]
    return out
def state_of(R):
    F = 0
    for a in R:
        for b in R:
            if a != b: F |= 1 << pair_of[((a-b)**2) % m]
    return F
def popc(F): return bin(F).count('1')

def run_cliq(insts):
    """insts: list of (mode, forbidden list). returns list of raw output blocks."""
    inp = f"{m} {BUDGET}\n" + "".join(f"{mode} {len(Fl)} " + " ".join(map(str, Fl)) + "\n" for mode, Fl in insts)
    out = subprocess.run(["./cliq"], input=inp, capture_output=True, text=True).stdout.splitlines()
    res = []; i = 0
    for mode, _ in insts:
        if mode[0] == 'e':
            om, cnt = map(int, out[i].split()); i += 1
            cl = [list(map(int, out[i+j].split())) for j in range(cnt)]; i += cnt
            res.append((om, cl))
        elif mode[0] == 'c':
            parts = list(map(int, out[i].split())); i += 1
            res.append((parts[0], parts[1:]))
        else:
            res.append((int(out[i]), None)); i += 1
    return res

cand = defaultdict(dict)     # F -> {F_actual: (size, R)}
expanded = set()
Sigma = {S}

def add_cand(F, R):
    Fa = state_of(R)
    if Fa not in cand[F] or cand[F][Fa][0] < len(R):
        cand[F][Fa] = (len(R), sorted(R))
    Sigma.add(Fa)

def expand(F):
    """generate candidates for state F"""
    Fl = fset(F)
    om, cl = run_cliq([(f"e{ENUMCAP}", Fl)])[0]
    states = {}
    for R in cl:
        Fa = state_of(R)
        if Fa not in states: states[Fa] = R
    for Fa, R in states.items(): add_cand(F, R)
    # target states to try: shrink each enumerated state by one pair (top TOPN states by fewest pairs), and S minus one pair
    targets = set()
    top = sorted(states, key=popc)[:TOPN]
    for Fa in top:
        for i in range(P):
            if Fa >> i & 1: targets.add(Fa & ~(1 << i))
    for i in range(P): targets.add(S & ~(1 << i))
    if TWOPAIR:
        for Fa in top[:3]:
            bits = [i for i in range(P) if Fa >> i & 1]
            for a in range(len(bits)):
                for b in range(a+1, len(bits)):
                    targets.add(Fa & ~(1 << bits[a]) & ~(1 << bits[b]))
        for a in range(P):
            for b in range(a+1, P):
                targets.add(S & ~(1 << a) & ~(1 << b))
    insts = [("c", sorted(set(Fl) | set(Dset(Fp)))) for Fp in targets]
    res = run_cliq(insts)
    for (om2, R) in res:
        if R: add_cand(F, R)
    expanded.add(F)
    return om

def value_iteration():
    """W_hat over Sigma. Unexpanded states get the monotone extension max over expanded supersets."""
    Sig = sorted(Sigma)
    W = {F: 0.0 for F in Sig}
    exp_list = [F for F in Sig if F in expanded]
    for it in range(200):
        Wn = {}
        for F in Sig:
            if F in expanded and cand[F]:
                Wn[F] = max(log(sz) + 0.5*W[Fa] for Fa, (sz, R) in cand[F].items())
            else:
                Wn[F] = max([W[G] for G in exp_list if (G & F) == F] + [0.0])   # G superset of F
        diff = max(abs(Wn[F]-W[F]) for F in Sig); W = Wn
        if diff < 1e-12: break
    return W

def follow(W, F, steps=30):
    chain = []
    for _ in range(steps):
        if F not in expanded or not cand[F]: break
        Fa, (sz, R) = max(cand[F].items(), key=lambda kv: log(kv[1][0]) + 0.5*W[kv[0]])
        chain.append((F, sz, R, Fa)); F = Fa
    return chain

def chain_value(chain):
    """value of the realised chain assuming it is eventually periodic in states"""
    states = [c[0] for c in chain] + [chain[-1][3]]
    first = {}
    for i, s in enumerate(states):
        if s in first:
            pre, per = first[s], i - first[s]; break
        first[s] = i
    else:
        return None, None, None
    sizes = [c[1] for c in chain]
    val = sum(log(sizes[k]) / 2**k for k in range(pre)) + sum(log(sizes[pre+j]) / 2**(pre+j) for j in range(per)) / (1 - 2.0**-per)
    return val, pre, per

t0 = time.time()
best_val = 0
for rnd in range(ROUNDS):
    # expand: states on the current optimal path plus top unexpanded by extension value
    if rnd == 0:
        to_expand = [S]
    else:
        W = value_iteration()
        path = follow(W, S)
        on_path = {c[3] for c in path} | {c[0] for c in path}
        # alternatives: best few candidate targets from path states that are not yet expanded
        alts = []
        for F in on_path:
            if F in expanded:
                for Fa, (sz, R) in cand[F].items():
                    if Fa not in expanded and popc(Fa) >= MINPAIRS:
                        alts.append((log(sz) + 0.5*W[Fa], Fa))
        alts.sort(reverse=True)
        seenA = set(); altF = []
        for v, Fa in alts:
            if Fa not in seenA: seenA.add(Fa); altF.append(Fa)
        to_expand = [F for F in on_path if F not in expanded and popc(F) >= MINPAIRS] + altF[:TOPN]
    for F in to_expand:
        if F not in expanded:
            t1 = time.time(); om = expand(F)
            print(f"   expanded state with {popc(F)} pairs: omega={om}, {len(cand[F])} candidates, {time.time()-t1:.1f}s", flush=True)
    W = value_iteration()
    path = follow(W, S)
    # policy-driven refinement: for path states, try the most valuable states as targets
    if rnd >= 1:
        topstates = sorted([F for F in Sigma if popc(F) >= MINPAIRS], key=lambda F: -W[F])[:KTOP]
        for F, sz, R, Fa in path:
            tried = tried_targets.setdefault(F, set())
            tg = [Fp for Fp in topstates if Fp not in tried and Fp not in cand[F]]
            if not tg: continue
            Fl = fset(F)
            res = run_cliq([("c", sorted(set(Fl) | set(Dset(Fp)))) for Fp in tg])
            for Fp, (om2, R2) in zip(tg, res):
                tried.add(Fp)
                if R2: add_cand(F, R2)
        W = value_iteration()
        path = follow(W, S)
    val, pre, per = chain_value(path)
    gamma = 0.5 + W[S] / (4*log(m))
    print(f"round {rnd}: |Sigma|={len(Sigma)} expanded={len(expanded)} W(S)>={W[S]:.6f} gamma>={gamma:.10f} "
          f"path sizes={[c[1] for c in path][:14]} realised value={val} pre={pre} per={per} t={time.time()-t0:.0f}s", flush=True)
    if val and val > best_val + 1e-12:
        best_val = val
        pickle.dump({"m": m, "pairs": pairs, "chain": [(c[0], c[1], c[2], c[3]) for c in path], "W": W[S], "pre": pre, "per": per},
                    open(f"best_{m}.pkl", "wb"))
print("final gamma lower bound", 0.5 + best_val/(4*log(m)))
